/// 야외 위치가 낡았을 때 **직접 한 건 요청할지**를 정하는 정책.
///
/// ## 왜 필요한가 — 스트림이 약속을 안 지킨다
///
/// `core/service_locator.dart`의 `positionStreamSettings()`는 안드로이드에
/// `distanceFilter: 0`, `intervalDuration: 1초`를 준다. 그런데 실기기(더현대
/// 앞 야외, 2026-08-13)에서 진단 칩이 찍은 좌표 사이 간격은 다음과 같았다:
///
///   +15.5s · +23.3s · +36.2s · +36.4s
///
/// 1초를 요청했는데 15~36초에 한 건이 왔다. 같은 순간 화면의 "위치 갱신"
/// 버튼(`Geolocator.getCurrentPosition`)은 누를 때마다 즉시 새 좌표를 돌려줬다.
/// 스트림 설정 자체는 요청한 대로 나가고 있다 — `positionStreamSettings()`가 준
/// 1초는 네이티브에서 `setIntervalMillis`/`setMinUpdateIntervalMillis`로 그대로
/// 변환된다. 그쪽으로 더 열 여지는 없다.
///
/// 그래서 스트림을 믿되, 조용한 구간만 일회성 조회로 메운다. 사용자가 손으로
/// 눌러 되던 일을 앱이 대신 하는 것이고, 그 경로는 이미 동작이 확인돼 있다.
///
/// ## 원인은 확정됐다 — 스트림이 벙어리였다
///
/// 진단 칩(`indoor_entry_gps.dart`의 `describeGpsBuildingJudgement`)을 달고 다시
/// 걸었더니(더현대 앞, 2026-08-13 15:57~16:00) 네 건 모두 이렇게 찍혔다.
///
///   `+8.1s · 직접 · 재시작1` · `+3.4s · 직접 · 재시작1`
///   `+9.0s · 직접 · 재시작1` · `+7.9s · 직접 · 재시작1`
///
/// `직접`은 그 좌표가 스트림이 아니라 **이 파일의 일회성 조회로 들어왔다**는
/// 뜻이고, `재시작1`은 스트림이 한 번도 닫히지 않았다는 뜻이다. 즉 스트림은
/// 열린 채로 좌표를 **한 건도** 주지 않았다. 기기가 좌표를 못 만든 것이 아니다 —
/// 같은 시간에 일회성 조회는 3~9초마다 멀쩡히 받아 왔다.
///
/// 까닭은 [streamFirstFixTimeout] 주석에 있다(포그라운드 서비스 바인딩 경합).
/// 그 감시를 붙였으므로 스트림은 이제 스스로 되살아난다.
///
/// ## 그래도 이 파일은 남는다
///
/// 벙어리 구간([streamFirstFixTimeout]) 동안 화면을 떠받치는 것이 여기다.
/// 스트림이 정상으로 돌아오면 [gpsFixMaxAge]에 걸리지 않아 저절로 조용해진다 —
/// **지우는 것이 아니라 안 쓰이게 되는 것이 정상 상태다.**
///
/// ## 어디서 깨지는가
///
/// - **요청이 겹치면 안 된다.** 일회성 조회는 응답까지 수 초 걸릴 수 있어,
///   간격만 보고 계속 쏘면 요청이 쌓이고 배터리만 태운다. [requestInFlight]로 막는다.
/// - **스트림이 정상인 기기에서는 한 번도 발화하면 안 된다.** [maxAge]가 스트림
///   주기(1초)보다 넉넉해야 하는 이유다. 3초면 1초 스트림에서는 절대 안 걸리고,
///   위 실측처럼 15초 넘게 비는 구간에서는 반드시 걸린다.
/// - **실내에서는 아예 돌면 안 된다.** 실내 위치의 주인은 PDR이고, 여기서 좌표를
///   더 부지런히 가져와 봐야 건물 밖 점만 자주 찍힌다. 그 판단은 호출자가 한다.
library;

/// 마지막 좌표가 이보다 오래되면 직접 한 건 요청한다.
///
/// 스트림이 약속대로 1초에 한 번 주는 기기에서는 이 값에 절대 닿지 않는다 —
/// 그런 기기에서 추가 요청이 나가면 배터리만 쓰고 얻는 것이 없다.
const gpsFixMaxAge = Duration(seconds: 3);

/// 지금 일회성 위치 조회를 보내야 하는지.
///
/// [lastFixReceivedAt]은 좌표를 **받은** 시각이다(기기가 찍은 시각이 아니다).
/// 낡음의 기준은 "화면이 얼마나 오래 옛 위치를 보여주고 있는가"이므로, 고정된
/// 좌표를 반복해서 받는 경우까지 신선하다고 보면 안 된다.
///
/// 아직 한 건도 못 받았으면([lastFixReceivedAt]이 null) 즉시 요청한다 — 스트림
/// 첫 좌표가 늦는 기기에서 지도가 한참 빈 채로 열리는 것을 막는다.
bool shouldRequestFreshFix({
  required DateTime? lastFixReceivedAt,
  required DateTime now,
  required bool requestInFlight,
  Duration maxAge = gpsFixMaxAge,
}) {
  if (requestInFlight) return false;
  if (lastFixReceivedAt == null) return true;
  return now.difference(lastFixReceivedAt) >= maxAge;
}

/// 닫힌 위치 스트림을 다시 열기까지 기다리는 첫 간격.
///
/// 짧게 잡는 이유는 정상 복구가 흔하기 때문이다 — 스트림이 순간적으로 닫히는
/// 경우가 대부분이고, 그때 30초를 기다리면 그 30초 동안 화면이 멈춘다.
const streamRetryMinDelay = Duration(seconds: 2);

/// 재연결 간격의 상한.
const streamRetryMaxDelay = Duration(seconds: 30);

/// 실내에 있을 때의 [gpsFixMaxAge].
///
/// **실내에서도 좌표는 받아야 한다.** 화면에 그리려는 것이 아니라 "이 사람이
/// 건물을 나갔는가"를 판정할 입력이 필요해서다. 그 판정의 유일한 입력이 GPS인데,
/// 예전에는 실내라는 이유로 일회성 조회를 아예 막아 두었다. 스트림까지 조용하면
/// 실내에 있는 동안 좌표가 **한 건도** 안 들어오고, 이탈 판정은 영영 발화하지
/// 않는다 — 나갔는데도 실내 위치가 계속 그려지던 것이 이것이다.
///
/// 야외보다 느슨하게 잡는 이유는 쓰임이 다르기 때문이다. 야외에서는 이 좌표가
/// 화면의 내 위치라 1초라도 낡으면 눈에 띄지만, 실내에서는 위치의 주인이 PDR이고
/// GPS는 판정에만 쓰인다. 문을 나선 뒤 5초 안에 전환되면 충분하다.
const indoorGpsFixMaxAge = Duration(seconds: 5);

/// 스트림을 연 뒤 이 시간 안에 좌표가 한 건도 안 오면 **죽은 것으로 본다.**
///
/// ## 왜 "닫힘"만으로는 부족한가
///
/// geolocator 안드로이드의 `StreamHandlerImpl.onListen`은 포그라운드 서비스
/// 바인딩이 아직 안 끝났으면 위치 요청을 걸지 않고 **그냥 돌아선다.** Dart에는
/// 에러도, 종료도 가지 않는다. 그래서 스트림은 열린 채로 평생 벙어리가 되고,
/// `onDone`을 붙여 둬도 걸리지 않는다.
///
/// 바인딩은 `bindService`라 비동기다. 앱이 시작하자마자 지도가 구독하면 이
/// 경합에 그대로 진다 — 실기기 로그에서 `Binding to location service` 바로 뒤에
/// `Location background service has not started correctly`가 찍혔다.
///
/// ## 왜 하필 이 길이인가
///
/// 짧으면 **느릴 뿐 살아 있는 스트림**을 끊어 버린다. 그러면 좌표가 올 때마다
/// 재등록이 겹쳐 오히려 더 느려진다. 실측에서 기기가 좌표를 만들어 낸 간격은
/// 3.4~9.0초였으므로, 그보다 넉넉히 위에 둔다.
///
/// 길면 시작 직후 스트림이 벙어리인 구간이 그만큼 길어지는데, 그동안 화면은
/// [shouldRequestFreshFix]의 일회성 조회가 떠받치므로 비어 있지는 않다.
const streamFirstFixTimeout = Duration(seconds: 12);

/// 다음 재연결까지 기다릴 시간. 실패가 이어지면 배로 늘리고 [streamRetryMaxDelay]
/// 에서 멈춘다.
///
/// **간격을 늘리는 이유는 영구 실패 때문이다.** 위치 권한이 거부돼 있거나 기기의
/// 위치 서비스가 꺼져 있으면 스트림은 열자마자 닫힌다. 고정 간격으로 다시 걸면
/// 그 상태에서 2초마다 채널을 두드리며 배터리만 태우고, 고쳐지는 것은 없다.
///
/// 반대로 상한이 없으면 안 된다. 잠깐 끊겼다 돌아오는 기기에서 간격이 분 단위로
/// 벌어지면, 신호가 멀쩡해진 뒤에도 화면은 한참 멈춰 있다.
Duration nextStreamRetryDelay(Duration current) {
  final doubled = current * 2;
  return doubled > streamRetryMaxDelay ? streamRetryMaxDelay : doubled;
}
