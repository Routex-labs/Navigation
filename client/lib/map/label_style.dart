/// 지도 위 **텍스트 라벨**의 색·헤일로·보조 라벨 크기.
///
/// 라벨 레이어가 여럿이라 값이 한 곳에 있어야 층을 오갈 때 글씨가 달라 보이지
/// 않는다. 위계는 **두 단계뿐이다** — 매장명과 그보다 한 단계 옅은 편의시설·POI
/// 이름. 왜 둘로 끝내는지는 `docs/client/map-style-rules.md`.
library;

/// 매장명 라벨 색. 도면에서 사용자가 실제로 찾는 대상이다.
const mapLabelStoreColor = '#444846';

/// 편의시설·POI 이름 색. [mapLabelStoreColor]와 같은 계열에서 한 단계 옅다 —
/// **아이콘이 주 신호이고 이름은 보조**다.
///
/// 흰 도면 위 대비 약 4.9:1로 본문 기준(4.5:1)을 넘긴다. 더 옅게 잡으면 위계는
/// 뚜렷해지지만 밝은 도면에서 읽히지 않는다.
const mapLabelFacilityColor = '#6B706A';

/// 라벨 헤일로. 도면 폴리곤·경로선 위에서 글자 획을 살린다.
const mapLabelHaloColor = '#FFFFFF';

/// 헤일로 두께. 실내가 1.2, 야외가 1.0으로 갈라져 있던 것을 굵은 쪽으로 맞췄다 —
/// 야외 오버레이는 매장 강조 fill 위에 라벨이 얹히는 경우가 있어 1.0에서는 획이
/// 배경에 먹혔다.
const mapLabelHaloWidth = 1.2;

/// 폴리곤 맞춤을 쓰지 않는 라벨의 **고정** 글자 크기(px).
///
/// 실내 화면의 매장명만 폴리곤 크기에 맞춰 변하고([store_label_fit.dart]) 나머지는
/// 전부 이 값이다. 아이콘이 중심을 차지하는 라벨은 [mapLabelBelowIconOffset]만큼
/// **폴리곤 밖으로** 내려 그리므로 맞춤 계산의 전제가 성립하지 않는다.
///
/// 매장명 밴드(12~17)와 같은 대역에 있어야 도면이 "매장명"과 "시설명" 두 덩어리로
/// 갈라져 보이지 않는다.
const mapLabelFixedTextSize = 13.0;

/// 고정 크기 라벨의 줄바꿈 폭(em). 실내 매장명은 feature마다 계산해 싣지만
/// ([kStoreLabelMaxWidthProperty]) 크기가 고정인 쪽은 폭도 고정이다.
const mapLabelFixedMaxWidth = 6.0;

/// 아이콘이 폴리곤 중심(centroid)을 차지하는 라벨에서 이름을 내리는 오프셋(em).
///
/// 실내 화면과 지도 오버레이가 **같은 값**을 써야 아이콘과 이름의 간격이 두 곳에서
/// 같아 보인다.
///
/// **하한은 헤일로다.** 빈 간격(`오프셋 − 아이콘 반지름`)이 [mapLabelHaloWidth]
/// 아래로 내려가면 글자 헤일로가 아이콘의 흰 테두리를 파고든다. 오프셋은 em인데
/// 아이콘은 고정 px이라 글자가 작을수록 간격이 좁아지고, 가장 빡빡한 12px에서
/// 0.6em이면 간격이 정확히 하한과 같다 — **더 줄이려면 오프셋이 아니라 아이콘
/// 크기나 헤일로를 손봐야 한다.**
const mapLabelBelowIconOffset = <double>[0, 0.6];
