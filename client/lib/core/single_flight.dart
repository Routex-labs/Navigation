/// 같은 작업이 **겹쳐 도는 것**을 막는다. 이미 돌고 있으면 새 요청을 버린다.
///
/// 대중교통 조회에서 실기기 로그로 확인한 문제를 막으려고 만들었다 — 같은 조회가
/// 2~3번 연달아 나갔고(응답 세 줄이 사이에 아무 로그 없이 붙어 있었다), 그만큼
/// API 쿼터를 배로 태웠다. 뒤늦게 돌아온 응답이 시트를 하나 더 얹으면 사용자는
/// 같은 목록을 두 번 닫아야 한다.
///
/// 큐가 아니라 **버리는** 쪽인 이유는, 겹친 요청이 어차피 같은 답을 받아 오기
/// 때문이다. 줄을 세워 두면 사용자가 이미 결과를 보고 있는데 뒤에서 같은 조회가
/// 한 번 더 나가고 화면이 다시 그려진다.
class SingleFlight {
  bool _busy = false;

  /// 지금 작업이 돌고 있는지.
  bool get isBusy => _busy;

  /// [task]를 실행한다. 이미 돌고 있으면 실행하지 않고 [onDuplicate]만 부른다.
  ///
  /// **[task]가 예외를 던져도 잠금은 풀린다.** 여기서 새면 그 뒤로 이 작업이
  /// 영영 실행되지 않는데, 화면에는 아무 반응이 없어 원인을 찾기가 가장 어렵다.
  /// 예외는 삼키지 않고 그대로 올려 보낸다 — 잠금 관리가 오류 처리까지 대신하면
  /// 호출부가 실패를 알 방법이 없다.
  Future<void> run(
    Future<void> Function() task, {
    void Function()? onDuplicate,
  }) async {
    if (_busy) {
      onDuplicate?.call();
      return;
    }
    _busy = true;
    try {
      await task();
    } finally {
      _busy = false;
    }
  }
}
