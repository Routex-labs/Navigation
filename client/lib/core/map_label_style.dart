/// 지도 위 **텍스트 라벨**의 색·헤일로·보조 라벨 크기. 실내 화면
/// ([FloorPlanView])과 야외 지도의 실내 오버레이가 같은 도면을 그리므로 두 곳이
/// 같은 값을 써야 한다 — [map_route_style.dart]·[map_palette.dart]와 같은 이유로
/// core에 둔다.
///
/// ## 왜 모았나 — 값이 다섯 갈래로 갈라져 있었다
///
/// 라벨 레이어를 늘릴 때마다 그 자리에서 색과 헤일로를 골라 넣은 결과, 같은
/// 도면 위에 **글자색 세 종류**가 떠 있었다.
///
/// | 화면 | 레이어 | 색 | 헤일로 | 크기 |
/// |---|---|---|---|---|
/// | 실내 | 매장명 | `#444846` | 1.2 | 9~18 (폴리곤 맞춤) |
/// | 실내 | 편의시설 이름 | `#444846` | 1.2 | 9~18 (폴리곤 맞춤) |
/// | 실내 | POI 이름 | `#4F5451` | 1.0 | 10 고정 |
/// | 야외 | 매장명 | `#333333` | 1.0 | 11 고정 |
/// | 야외 | 편의시설 이름 | `#333333` | 1.0 | 11 고정 |
///
/// 셋 다 "진한 회색"이라 하나씩 보면 틀린 값이 없는데, 한 화면에 섞이면 어떤
/// 글자가 왜 더 진한지 설명할 수 없다. 층을 바꾸거나 실내/야외를 오갈 때 같은
/// 매장 이름의 색이 바뀌는 것도 여기서 나왔다.
///
/// ## 지금 규칙 — 두 단계뿐이다
///
/// 우연히 생긴 세 값을 **의도한 두 값**으로 줄인다.
///
///  - [mapLabelStoreColor] — 매장명. 도면에서 사용자가 실제로 찾는 대상이다.
///  - [mapLabelFacilityColor] — 편의시설·POI 이름. **아이콘이 주 신호이고 이름은
///    보조**라 한 단계 옅다. 화장실이 어디인지는 아이콘이 말하고, 이름은
///    「ATM (하나은행)」처럼 아이콘이 못 말하는 것만 덧붙인다.
///
/// 두 단계로 끝내는 이유는 상용 지도와 같다 — 색 단계를 늘릴수록 "이 글자가 저
/// 글자보다 중요한가"를 매번 판단해야 하는데, 실내 도면에는 그 판단을 지탱할
/// 랭킹 데이터(방문량·중요도)가 없다.
library;

/// 매장명 라벨 색. 실내에서 이미 쓰던 값을 단일 출처로 승격했다(다수가 이 값을
/// 쓰고 있었고, 도면 배경([map_palette.dart])이 초록 기가 도는 밝은 회색이라
/// 순수 회색보다 이쪽이 어울린다).
const mapLabelStoreColor = '#444846';

/// 편의시설·POI 이름 색. [mapLabelStoreColor]와 같은 색상 계열에서 한 단계 옅다.
///
/// 흰 도면(`#FFFFFF`) 위 대비 약 4.9:1로 본문 기준(4.5:1)을 넘긴다. 더 옅게
/// 잡으면 매장명과의 위계는 뚜렷해지지만 밝은 도면에서 읽히지 않는다 — 위계는
/// 색 하나가 아니라 **아이콘 유무**가 이미 절반을 맡고 있으므로 여기서 무리하지
/// 않는다.
const mapLabelFacilityColor = '#6B706A';

/// 라벨 헤일로. 도면 폴리곤·경로선 위에서 글자 획을 살린다.
const mapLabelHaloColor = '#FFFFFF';

/// 헤일로 두께. 실내가 1.2, 야외가 1.0으로 갈라져 있던 것을 굵은 쪽으로 맞췄다 —
/// 야외 오버레이는 매장 강조 fill 위에 라벨이 얹히는 경우가 있어 1.0에서는 획이
/// 배경에 먹혔다.
const mapLabelHaloWidth = 1.2;

/// 편의시설·POI 이름의 **고정** 글자 크기(px).
///
/// 매장명만 폴리곤 크기에 맞춰 변하고([store_label_fit.dart]) 이쪽은 고정이다.
/// 폴리곤 맞춤은 "글자가 그 폴리곤 **안에** 들어가는가"를 재는 계산인데, 편의시설
/// 이름은 아이콘이 중심을 차지해 [mapLabelBelowIconOffset]만큼 **폴리곤 밖으로**
/// 내려 그린다. 즉 맞춤 계산의 전제가 성립하지 않는다 — 실제로 「취식 가능장소」
/// 처럼 넓은 시설은 상한(18px)까지 커진 이름이 아래 이웃 매장을 덮었다.
///
/// 값 11은 야외 오버레이가 이미 쓰던 크기다. 두 화면에서 같은 시설 이름이 같은
/// 크기로 보이게 하려면 실내도 이 값이어야 한다.
const mapLabelFacilityTextSize = 11.0;

/// 편의시설·POI 이름의 줄바꿈 폭(em). 매장명은 feature마다 계산해 싣지만
/// ([kStoreLabelMaxWidthProperty]) 크기가 고정인 이쪽은 폭도 고정이다.
const mapLabelFacilityMaxWidth = 6.0;

/// 아이콘이 폴리곤 중심(centroid)을 차지하는 라벨에서 이름을 내리는 오프셋(em).
///
/// 실내 편의시설·POI 라벨과 야외 편의시설 라벨이 **같은 값**을 써야 두 화면에서
/// 아이콘과 이름의 간격이 같아 보인다.
const mapLabelBelowIconOffset = <double>[0, 1.6];
