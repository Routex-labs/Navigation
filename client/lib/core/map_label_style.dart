/// 지도 위 **텍스트 라벨**의 색·헤일로·보조 라벨 크기. 실내 화면
/// ([FloorPlanView])과 야외 지도의 실내 오버레이가 같은 도면을 그리므로 두 곳이
/// 같은 값을 써야 한다 — [map_route_style.dart]·[map_palette.dart]와 같은 이유로
/// core에 둔다.
///
/// ## 왜 모았나 — 값이 다섯 갈래로 갈라져 있었다
///
/// 라벨 레이어를 늘릴 때마다 그 자리에서 색과 헤일로를 골라 넣은 결과, 같은
/// 도면 위에 **글자색 세 종류**가 떠 있었다.
///
/// | 화면 | 레이어 | 색 | 헤일로 | 크기 |
/// |---|---|---|---|---|
/// | 실내 | 매장명 | `#444846` | 1.2 | 9~18 (폴리곤 맞춤) |
/// | 실내 | 편의시설 이름 | `#444846` | 1.2 | 9~18 (폴리곤 맞춤) |
/// | 실내 | POI 이름 | `#4F5451` | 1.0 | 10 고정 |
/// | 야외 | 매장명 | `#333333` | 1.0 | 11 고정 |
/// | 야외 | 편의시설 이름 | `#333333` | 1.0 | 11 고정 |
///
/// 셋 다 "진한 회색"이라 하나씩 보면 틀린 값이 없는데, 한 화면에 섞이면 어떤
/// 글자가 왜 더 진한지 설명할 수 없다. 층을 바꾸거나 실내/야외를 오갈 때 같은
/// 매장 이름의 색이 바뀌는 것도 여기서 나왔다.
///
/// ## 지금 규칙 — 두 단계뿐이다
///
/// 우연히 생긴 세 값을 **의도한 두 값**으로 줄인다.
///
///  - [mapLabelStoreColor] — 매장명. 도면에서 사용자가 실제로 찾는 대상이다.
///  - [mapLabelFacilityColor] — 편의시설·POI 이름. **아이콘이 주 신호이고 이름은
///    보조**라 한 단계 옅다. 화장실이 어디인지는 아이콘이 말하고, 이름은
///    「ATM (하나은행)」처럼 아이콘이 못 말하는 것만 덧붙인다.
///
/// 두 단계로 끝내는 이유는 상용 지도와 같다 — 색 단계를 늘릴수록 "이 글자가 저
/// 글자보다 중요한가"를 매번 판단해야 하는데, 실내 도면에는 그 판단을 지탱할
/// 랭킹 데이터(방문량·중요도)가 없다.
library;

/// 매장명 라벨 색. 실내에서 이미 쓰던 값을 단일 출처로 승격했다(다수가 이 값을
/// 쓰고 있었고, 도면 배경([map_palette.dart])이 초록 기가 도는 밝은 회색이라
/// 순수 회색보다 이쪽이 어울린다).
const mapLabelStoreColor = '#444846';

/// 편의시설·POI 이름 색. [mapLabelStoreColor]와 같은 색상 계열에서 한 단계 옅다.
///
/// 흰 도면(`#FFFFFF`) 위 대비 약 4.9:1로 본문 기준(4.5:1)을 넘긴다. 더 옅게
/// 잡으면 매장명과의 위계는 뚜렷해지지만 밝은 도면에서 읽히지 않는다 — 위계는
/// 색 하나가 아니라 **아이콘 유무**가 이미 절반을 맡고 있으므로 여기서 무리하지
/// 않는다.
const mapLabelFacilityColor = '#6B706A';

/// 라벨 헤일로. 도면 폴리곤·경로선 위에서 글자 획을 살린다.
const mapLabelHaloColor = '#FFFFFF';

/// 헤일로 두께. 실내가 1.2, 야외가 1.0으로 갈라져 있던 것을 굵은 쪽으로 맞췄다 —
/// 야외 오버레이는 매장 강조 fill 위에 라벨이 얹히는 경우가 있어 1.0에서는 획이
/// 배경에 먹혔다.
const mapLabelHaloWidth = 1.2;

/// 폴리곤 맞춤을 쓰지 않는 라벨의 **고정** 글자 크기(px).
///
/// 실내 화면의 매장명만 폴리곤 크기에 맞춰 변하고([store_label_fit.dart]) 나머지는
/// 전부 이 값이다 — 실내 편의시설·POI 이름, 그리고 **지도 오버레이의 매장명까지**.
///
/// 폴리곤 맞춤은 "글자가 그 폴리곤 **안에** 들어가는가"를 재는 계산인데, 아이콘이
/// 중심을 차지하는 라벨은 [mapLabelBelowIconOffset]만큼 **폴리곤 밖으로** 내려
/// 그린다. 즉 맞춤 계산의 전제가 성립하지 않는다 — 실제로 「취식 가능장소」처럼
/// 넓은 시설은 상한(18px)까지 커진 이름이 아래 이웃 매장을 덮었다.
///
/// 처음에는 야외 오버레이가 쓰던 11이었는데, 매장명 밴드를 접근성 피드백으로
/// 12~17로 올리면서 **그 안에 들어오도록** 13으로 함께 올렸다. 밴드 밖으로
/// 벗어나면 도면이 "매장명"과 "시설명" 두 덩어리로 갈라져 보인다.
///
/// 오버레이 매장명이 11에서 이 값으로 합류한 이유도 같다. 마커를 전부 한 크기로
/// 맞추고 나니([kIndoorMarkerLogicalPx]) 같은 도면 위에서 매장 이름만 두 px 작아
/// 아이콘 대비 더 작아 보였다.
const mapLabelFixedTextSize = 13.0;

/// 고정 크기 라벨의 줄바꿈 폭(em). 실내 매장명은 feature마다 계산해 싣지만
/// ([kStoreLabelMaxWidthProperty]) 크기가 고정인 쪽은 폭도 고정이다.
const mapLabelFixedMaxWidth = 6.0;

/// 아이콘이 폴리곤 중심(centroid)을 차지하는 라벨에서 이름을 내리는 오프셋(em).
///
/// 실내 화면과 지도 오버레이가 **같은 값**을 써야 두 곳에서 아이콘과 이름의
/// 간격이 같아 보인다.
///
/// ## 값의 근거 — 아이콘 반지름 + 손가락 두께가 아니라 눈에 보이는 여백
///
/// 이 오프셋은 **글자 크기의 배수(em)** 이고, 재는 기준점은 폴리곤 중심이다.
/// 그래서 화면에 보이는 빈 간격은 `오프셋 - 아이콘 반지름`이다. 아이콘이
/// [kIndoorMarkerLogicalPx](12 논리 px, 반지름 6)이고 글자가
/// [mapLabelFixedTextSize](13)일 때:
///
/// | 오프셋 | 중심에서 | 빈 간격 |
/// |---|---|---|
/// | 1.6em (예전) | 20.8px | **14.8px** |
/// | 0.75em (지금) | 9.75px | 3.75px |
///
/// 1.6em은 아이콘이 **배율 환산 없이** 4~6 논리 px로 그려지던 시절에 정해진
/// 값이다. 그때도 간격은 15px이었고 "이름이 아이콘에서 떨어져 나와 어느 아이콘의
/// 이름인지 모르겠다"가 실제 피드백이었다. 아이콘을 제 크기로 되돌린 지금은
/// 더더욱 맞지 않는다.
///
/// **더 줄이지 않는 이유**: 0.5em 아래로 내리면 두 줄로 접힌 이름의 첫 줄이
/// 아이콘 헤일로에 닿는다. 글자 크기가 커질수록 em 오프셋도 함께 커지므로
/// 실내 매장명(12~17px 가변)에서도 비율이 유지된다.
const mapLabelBelowIconOffset = <double>[0, 0.75];
